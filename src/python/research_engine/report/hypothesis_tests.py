"""
src.report.hypothesis_tests
===========================
Out-of-Sample Statistical Gate, Bootstrap Resampling, Placebo Null Tests,
and Multiple Testing Regularization (F16).

Key Functionalities:
1. Hermetic Out-of-Sample Sealed Test Evaluation using `load_test_partition` with
   token="OOS_EVALUATION_AUTHORIZED" and cryptographic SHA-256 validation.
2. Stationary/Empirical Bootstrap 95% Confidence Intervals (10,000 resamples)
   for net expectancy after all transaction costs, swaps, and slippage.
3. Parametric Placebo Null Hypothesis Comparison (Student's t-test, Welch's t-test,
   Mann-Whitney U rank test, and Cohen's d effect size).
4. Statistical Acceptance Gate: Strategy qualifies for "GO" strictly if:
   - 95% CI Lower Bound > 0.0 (statistically significant positive net edge)
   - Statistically superior to moment-matched placebo (p < 0.05)
   - Across >= 2 instruments.
   Otherwise, transparent, reproducible "NO-GO" verdict.
5. Trial Registry Integration with Benjamini-Hochberg False Discovery Rate (FDR)
   and Holm-Bonferroni Family-Wise Error Rate (FWER) control across M trials.
"""

