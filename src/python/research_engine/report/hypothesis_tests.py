def bootstrap_confidence_interval(
    pnls: Sequence[float],
    n_bootstraps: int = 10_000,
    alpha: float = 0.05,
    seed: int = 42,
) -> Tuple[float, float, float]:
    """
    Computes empirical bootstrap confidence interval for net trade expectancy.

    Parameters
    ----------
    pnls : Sequence[float]
        Sequence of trade net PnLs.
    n_bootstraps : int, default 10_000
        Number of bootstrap resamples (mandated >= 10,000 for production grade).
    alpha : float, default 0.05
        Significance level (default 0.05 for 95% two-sided confidence interval).
    seed : int, default 42
        PRNG seed for reproducible resampling.

    Returns
    -------
    Tuple[float, float, float]
        (mean_pnl, ci_lower, ci_upper)
    """
    if len(pnls) == 0:
        return 0.0, 0.0, 0.0

    arr = np.asarray(pnls, dtype=np.float64)
    n = len(arr)
    if n == 1:
        val = float(arr[0])
        return val, val, val

    mean_val = float(np.mean(arr))
    if np.all(arr == arr[0]):
        return mean_val, mean_val, mean_val

    rng = np.random.default_rng(seed)
    boot_samples = rng.choice(arr, size=(n_bootstraps, n), replace=True)
    boot_means = np.mean(boot_samples, axis=1)

    ci_lower = float(np.percentile(boot_means, 100.0 * (alpha / 2.0)))
    ci_upper = float(np.percentile(boot_means, 100.0 * (1.0 - alpha / 2.0)))

    return mean_val, ci_lower, ci_upper


def bootstrap_net_expectancy(
    pnls: Sequence[float],
    n_bootstrap: int = 1000,
    ci: float = 0.95,
    seed: int = 42,
) -> Tuple[float, float, float]:
    """
    Alias wrapper strictly compatible with contract_harness.py and src.backtest.metrics.
    """
    alpha = 1.0 - ci
    return bootstrap_confidence_interval(
        pnls=pnls,
        n_bootstraps=n_bootstrap,
        alpha=alpha,
        seed=seed,
    )


def compare_against_placebo(
    empirical_pnls: Sequence[float],
    placebo_pnls: Sequence[float],
) -> Dict[str, Any]:
    """
    Performs rigorous statistical comparison of empirical strategy performance
    against moment-matched synthetic placebo data under the null hypothesis H0.

    Calculates:
    - Two-sample Student's t-test
    - Welch's t-test (unequal variances)
    - Mann-Whitney U rank-sum test (non-parametric)
    - Cohen's d effect size: (mu_1 - mu_2) / s_pooled

    Parameters
    ----------
    empirical_pnls : Sequence[float]
        Empirical trade net PnLs from real market data.
    placebo_pnls : Sequence[float]
        Trade net PnLs generated by running identical strategy logic on placebo ticks.

    Returns
    -------
    Dict[str, Any]
        Statistical comparison summary.
    """
    emp = np.asarray(empirical_pnls, dtype=np.float64)
    pla = np.asarray(placebo_pnls, dtype=np.float64)

    n_emp = len(emp)
    n_pla = len(pla)

    if n_emp == 0 or n_pla == 0:
        return {
            "t_stat": 0.0,
            "p_value": 1.0,
            "welch_t_stat": 0.0,
            "welch_p_value": 1.0,
            "mann_whitney_u": 0.0,
            "mann_whitney_p_value": 1.0,
            "cohens_d": 0.0,
            "empirical_mean": float(np.mean(emp)) if n_emp > 0 else 0.0,
            "placebo_mean": float(np.mean(pla)) if n_pla > 0 else 0.0,
            "empirical_std": float(np.std(emp, ddof=1)) if n_emp > 1 else 0.0,
            "placebo_std": float(np.std(pla, ddof=1)) if n_pla > 1 else 0.0,
            "statistically_superior": False,
        }

    emp_mean = float(np.mean(emp))
    pla_mean = float(np.mean(pla))
    emp_std = float(np.std(emp, ddof=1)) if n_emp > 1 else 0.0
    pla_std = float(np.std(pla, ddof=1)) if n_pla > 1 else 0.0

    # Student's t-test & Welch's t-test
    if emp_std == 0.0 and pla_std == 0.0:
        t_stat = 0.0
        p_val = 1.0 if emp_mean == pla_mean else 0.0
        welch_t = 0.0
        welch_p = p_val
    else:
        ttest_res = stats.ttest_ind(emp, pla, equal_var=True)
        t_stat = float(ttest_res.statistic)
        p_val = float(ttest_res.pvalue)

        welch_res = stats.ttest_ind(emp, pla, equal_var=False)
        welch_t = float(welch_res.statistic)
        welch_p = float(welch_res.pvalue)

    # Mann-Whitney U test
    try:
        mw_res = stats.mannwhitneyu(emp, pla, alternative="two-sided")
        mw_u = float(mw_res.statistic)
        mw_p = float(mw_res.pvalue)
    except Exception:
        mw_u = 0.0
        mw_p = 1.0

    # Cohen's d effect size
    if n_emp + n_pla > 2 and (emp_std > 0 or pla_std > 0):
        pooled_var = (((n_emp - 1) * (emp_std**2)) + ((n_pla - 1) * (pla_std**2))) / (n_emp + n_pla - 2)
        pooled_std = math.sqrt(max(1e-12, pooled_var))
        cohens_d = float((emp_mean - pla_mean) / pooled_std)
    else:
        cohens_d = 0.0

    # Statistical superiority requires empirical mean strictly higher than placebo AND p < 0.05
    stat_superior = (emp_mean > pla_mean) and (p_val < 0.05)

    return {
        "t_stat": t_stat,
        "p_value": p_val,
        "welch_t_stat": welch_t,
        "welch_p_value": welch_p,
        "mann_whitney_u": mw_u,
        "mann_whitney_p_value": mw_p,
        "cohens_d": cohens_d,
        "empirical_mean": emp_mean,
        "placebo_mean": pla_mean,
        "empirical_std": emp_std,
        "placebo_std": pla_std,
        "statistically_superior": stat_superior,
    }


def get_default_strategy_for_symbol(symbol: str) -> Any:
    """
    Returns the designated candidate strategy instance for a given symbol.
    For Boom & Crash indices, returns a Train-calibrated UserPostSpikeStrategy.
    """
    sym_lower = symbol.lower()
    if "boom" in sym_lower or "crash" in sym_lower:
        return UserPostSpikeStrategy.for_symbol(symbol=symbol, delay_ticks=3)
    elif "step" in sym_lower:
        return StepMeanReversionStrategy(symbol=symbol)
    else:
        return VolatilityBreakoutStrategy(symbol=symbol)


def evaluate_out_of_sample(
    test_files: Dict[str, Union[str, Path]],
    manifest_path: Union[str, Path],
    strategy_factory: Optional[Callable[[str], Any]] = None,
    token: str = OOS_AUTHORIZATION_TOKEN,
    initial_balance: float = 10000.0,
    trial_registry: Optional[TrialRegistry] = None,
    reason: str = "MILESTONE_5_OOS_EVALUATION",
    n_bootstraps: int = 10_000,
    n_ruin_sims: int = 5_000,
) -> Dict[str, Any]:
    """
    Executes hermetic out-of-sample evaluation across quarantined test partitions.

    Guarantees:
    1. Loads sealed test partition via load_test_partition with token authorization
       and SHA-256 manifest validation.
    2. Runs BacktestEngine with zero lookahead, full spread, gap slippage, and stop-outs.
    3. Runs parallel moment-matched Placebo simulation.
    4. Computes 95% bootstrap confidence intervals for net expectancy.
    5. Computes analytical and Monte Carlo ruin probabilities across capital ladder.
    6. Registers trials in TrialRegistry and evaluates FDR (Benjamini-Hochberg) / FWER (Holm).
    7. Emits unambiguous GO / NO-GO verdict per instrument.
    """
    results: Dict[str, Dict[str, Any]] = {}
    passed_instruments: List[str] = []
    failed_instruments: List[str] = []

    for symbol, path in test_files.items():
        logger.info(f"Initiating OOS Evaluation for '{symbol}' from {path}...")

        # 1. Quarantined test load
        test_df = load_test_partition(
            test_path=path,
            manifest_path=manifest_path,
            token=token,
            reason=reason,
            caller="src.report.hypothesis_tests.evaluate_out_of_sample",
        )

        # 2. Strategy instantiation
        factory = strategy_factory or get_default_strategy_for_symbol
        strategy_emp = factory(symbol)
        strategy_pla = factory(symbol)

        # 3. Empirical backtest execution
        spec = DERIV_SPECS.get(symbol, DERIV_SPECS["Boom 1000 Index"])
        engine_emp = BacktestEngine(initial_balance=initial_balance, spec=spec)
        metrics_emp = engine_emp.run(test_df, strategy_emp)

        closed_trades = engine_emp.account.closed_trades
        empirical_pnls = [float(t["net_pnl"]) for t in closed_trades]
        avg_lot = float(np.mean([float(t.get("lots", spec.volume_min)) for t in closed_trades])) if closed_trades else spec.volume_min

        # 4. Placebo calibration & simulation
        placebo_gen = PlaceboGenerator()
        placebo_gen.fit(test_df, spike_threshold=None)
        placebo_df = placebo_gen.generate(n_ticks=len(test_df), seed=42)

        engine_pla = BacktestEngine(initial_balance=initial_balance, spec=spec)
        metrics_pla = engine_pla.run(placebo_df, strategy_pla)
        placebo_pnls = [float(t["net_pnl"]) for t in engine_pla.account.closed_trades]

        # 5. Placebo statistical comparison
        placebo_comp = compare_against_placebo(empirical_pnls, placebo_pnls)

        # 6. Bootstrap 95% Confidence Interval (10,000 resamples)
        mean_pnl, ci_low, ci_high = bootstrap_confidence_interval(
            empirical_pnls,
            n_bootstraps=n_bootstraps,
            alpha=0.05,
            seed=42,
        )

        # 7. Ruin Theory Modeling across Standard & Demo Capital Ladder ($500 to $25,000)
        capital_ladder_df = evaluate_capital_ladder(
            trade_pnls=empirical_pnls,
            capitals=(500.0, 1000.0, 2500.0, 5000.0, 10000.0, 25000.0),
            n_simulations=n_ruin_sims,
            horizon_trades=1_000,
            seed=42,
        )
        ladder_dicts = capital_ladder_df.to_dicts()

        ruin_500 = next((row["ruin_prob_mc"] for row in ladder_dicts if row["capital_usd"] == 500.0), 1.0)
        ruin_1000 = next((row["ruin_prob_mc"] for row in ladder_dicts if row["capital_usd"] == 1000.0), 0.0)
        ruin_10000 = next((row["ruin_prob_mc"] for row in ladder_dicts if row["capital_usd"] == 10000.0), 0.0)

        # Compute mean win and mean loss magnitudes
        wins = [p for p in empirical_pnls if p > 0]
        losses = [p for p in empirical_pnls if p <= 0]
        mean_win = float(np.mean(wins)) if wins else 0.0
        mean_loss = float(np.mean(losses)) if losses else 0.0
        net_mean_per_lot = mean_pnl / max(avg_lot, 1e-6)

        # 8. Statistical Gate Evaluation
        # Strategy qualifies for GO iff:
        # - Net expectancy 95% CI lower bound > 0.0
        # - Empirical distribution significantly outperforms placebo (p < 0.05)
        # - Total closed trades >= 10
        has_min_trades = len(closed_trades) >= 10
        positive_ci = ci_low > 0.0
        beat_placebo = placebo_comp["statistically_superior"]

        gate_passed = has_min_trades and positive_ci and beat_placebo
        verdict = "GO" if gate_passed else "NO-GO"

        if gate_passed:
            passed_instruments.append(symbol)
        else:
            failed_instruments.append(symbol)

        # 9. Trial Registry Logging
        trial_id = None
        if trial_registry is not None:
            trial_id = trial_registry.register_trial(
                strategy_id=getattr(strategy_emp, "name", "Strategy"),
                symbol=symbol,
                params=getattr(strategy_emp, "get_params", lambda: {})(),
                p_value=placebo_comp["p_value"],
                t_stat=placebo_comp["t_stat"],
                sharpe=metrics_emp.get("sharpe_ratio", 0.0),
                notes=f"OOS Verdict: {verdict} | CI=[{ci_low:.4f}, {ci_high:.4f}] | Mean={mean_pnl:.4f}",
            )

        results[symbol] = {
            "symbol": symbol,
            "strategy": getattr(strategy_emp, "name", "Strategy"),
            "total_trades": len(closed_trades),
            "avg_lot": avg_lot,
            "win_rate": metrics_emp.get("win_rate", 0.0),
            "loss_rate": metrics_emp.get("loss_rate", 0.0),
            "mean_win": mean_win,
            "mean_loss": mean_loss,
            "profit_factor": metrics_emp.get("profit_factor", 0.0),
            "net_mean": mean_pnl,
            "net_mean_per_lot": net_mean_per_lot,
            "ci_lower": ci_low,
            "ci_upper": ci_high,
            "max_drawdown_usd": metrics_emp.get("max_drawdown_usd", 0.0),
            "max_drawdown_pct": metrics_emp.get("max_drawdown_pct", 0.0),
            "sharpe_ratio": metrics_emp.get("sharpe_ratio", 0.0),
            "sortino_ratio": metrics_emp.get("sortino_ratio", 0.0),
            "stop_outs_count": metrics_emp.get("stop_outs_count", 0),
            "final_equity": metrics_emp.get("final_equity", initial_balance),
            "demo_10k_pnl": metrics_emp.get("final_equity", initial_balance) - initial_balance,
            "placebo_comparison": placebo_comp,
            "p_value_placebo": placebo_comp["p_value"],
            "capital_ladder": ladder_dicts,
            "ruin_500": ruin_500,
            "ruin_1000": ruin_1000,
            "ruin_10000": ruin_10000,
            "verdict": verdict,
            "trial_id": trial_id,
        }

    # Project-wide decision
    # Acceptance criteria: Win on at least 2 instruments
    overall_verdict = "GO" if len(passed_instruments) >= 2 else "NO-GO"

    summary = {
        "evaluation_timestamp_utc": time_utc_str(),
        "total_instruments_evaluated": len(test_files),
        "passed_instruments_count": len(passed_instruments),
        "failed_instruments_count": len(failed_instruments),
        "passed_instruments": passed_instruments,
        "failed_instruments": failed_instruments,
        "overall_verdict": overall_verdict,
        "results_by_symbol": results,
    }

    return summary


def time_utc_str() -> str:
    """Returns current UTC timestamp in ISO 8601 format."""
    import time
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
